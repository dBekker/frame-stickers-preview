// Ориентировочная формула — замените на реальную тарификацию.
export function calcPrice(w, l, lam, sheets) {
  const lamMult = lam === 'глянцевый' ? 1.25 : lam === 'матовый' ? 1.18 : 1.0;
  const raw = w * l * 7.5 * lamMult * sheets;
  return Math.max(1500, Math.round(raw / 10) * 10);
}
